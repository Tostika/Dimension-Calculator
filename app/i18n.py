    def __init__(self, lang="ka"):
        self.lang = lang if lang in ("ka", "en") else "ka"

    def __call__(self, key, **kwargs):
        entry = TEXT.get(key)
        if entry is None:
            return key
        text = entry.get(self.lang) or entry.get("en") or key
        return text.format(**kwargs) if kwargs else text
